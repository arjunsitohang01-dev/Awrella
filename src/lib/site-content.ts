export type SiteContentKey = keyof typeof DEFAULT_SITE_CONTENT
export type SiteContentMap = Record<SiteContentKey, string>

export const SITE_CONTENT_KEYS = Object.keys(DEFAULT_SITE_CONTENT) as SiteContentKey[]

export function normalizeSiteContent(
  content?: Partial<Record<string, string | null | undefined>>,
): SiteContentMap {
  const normalized: SiteContentMap = { ...DEFAULT_SITE_CONTENT }

  if (!content) {
    return normalized
  }

  for (const key of SITE_CONTENT_KEYS) {
    const value = content[key]

    if (typeof value === 'string') {
      normalized[key] = value.trim()
    }
  }

  return normalized
}

export function sanitizeSiteContentInput(
  content?: Record<string, unknown>,
): Partial<SiteContentMap> {
  const sanitized: Partial<SiteContentMap> = {}

  if (!content) {
    return sanitized
  }

  for (const key of SITE_CONTENT_KEYS) {
    const value = content[key]

    if (typeof value === 'string') {
      sanitized[key] = value.trim()
      continue
    }

    if (value !== undefined && value !== null) {
      sanitized[key] = String(value).trim()
    }
  }

  return sanitized
}
